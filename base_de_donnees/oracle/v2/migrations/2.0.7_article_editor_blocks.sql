CREATE OR REPLACE PACKAGE BODY pkg_article_editor AS
    FUNCTION obtenir_id_statut_article(p_code VARCHAR2) RETURN NUMBER IS
        v_id NUMBER;
    BEGIN
        SELECT identifiant_statut_article
          INTO v_id
          FROM ref_statut_article
         WHERE code_statut = LOWER(TRIM(p_code));

        RETURN v_id;
    END obtenir_id_statut_article;

    FUNCTION generer_slug_article(p_titre VARCHAR2) RETURN VARCHAR2 IS
        v_base VARCHAR2(220 CHAR);
    BEGIN
        v_base := REGEXP_REPLACE(
            REGEXP_REPLACE(LOWER(TRIM(p_titre)), '[^a-z0-9]+', '-'),
            '(^-|-$)',
            ''
        );

        IF v_base IS NULL THEN
            v_base := 'article';
        END IF;

        RETURN SUBSTR(v_base, 1, 180) || '-' || LOWER(SUBSTR(RAWTOHEX(SYS_GUID()), 1, 12));
    END generer_slug_article;

    PROCEDURE creer_article_structure(
        p_identifiant_auteur_compte NUMBER,
        p_auteur_affiche VARCHAR2,
        p_titre VARCHAR2,
        p_resume VARCHAR2,
        p_contenu CLOB,
        o_identifiant_article OUT NUMBER
    ) IS
        v_statut_id NUMBER;
    BEGIN
        IF TRIM(p_titre) IS NULL OR LENGTH(TRIM(p_titre)) > 200 THEN
            RAISE_APPLICATION_ERROR(-20701, 'Titre article invalide.');
        END IF;

        IF TRIM(p_auteur_affiche) IS NULL OR LENGTH(TRIM(p_auteur_affiche)) > 120 THEN
            RAISE_APPLICATION_ERROR(-20702, 'Auteur affiche invalide.');
        END IF;

        IF TRIM(p_resume) IS NULL OR LENGTH(TRIM(p_resume)) > 500 THEN
            RAISE_APPLICATION_ERROR(-20703, 'Resume article invalide.');
        END IF;

        IF p_contenu IS NULL OR DBMS_LOB.GETLENGTH(p_contenu) = 0 THEN
            RAISE_APPLICATION_ERROR(-20710, 'Contenu article obligatoire.');
        END IF;

        v_statut_id := obtenir_id_statut_article('en_attente_validation');

        INSERT INTO article (
            identifiant_compte_auteur,
            identifiant_statut_article,
            auteur_affiche,
            titre,
            slug,
            resume,
            contenu
        ) VALUES (
            p_identifiant_auteur_compte,
            v_statut_id,
            TRIM(p_auteur_affiche),
            TRIM(p_titre),
            generer_slug_article(p_titre),
            TRIM(p_resume),
            p_contenu
        )
        RETURNING identifiant_article INTO o_identifiant_article;
    END creer_article_structure;

    PROCEDURE supprimer_blocs_article(
        p_identifiant_article NUMBER
    ) IS
    BEGIN
        DELETE FROM article_bloc
         WHERE identifiant_article = p_identifiant_article;
    END supprimer_blocs_article;

    PROCEDURE ajouter_bloc_texte(
        p_identifiant_article NUMBER,
        p_code_type_bloc VARCHAR2,
        p_ordre_affichage NUMBER,
        p_texte CLOB
    ) IS
        v_code_type_bloc VARCHAR2(30 CHAR) := LOWER(TRIM(p_code_type_bloc));
    BEGIN
        IF v_code_type_bloc NOT IN ('paragraphe', 'sous_titre') THEN
            RAISE_APPLICATION_ERROR(-20704, 'Type de bloc texte invalide.');
        END IF;

        IF p_texte IS NULL OR DBMS_LOB.GETLENGTH(p_texte) = 0 THEN
            RAISE_APPLICATION_ERROR(-20705, 'Texte de bloc obligatoire.');
        END IF;

        INSERT INTO article_bloc (
            identifiant_article,
            code_type_bloc,
            ordre_affichage,
            texte
        ) VALUES (
            p_identifiant_article,
            v_code_type_bloc,
            p_ordre_affichage,
            p_texte
        );
    END ajouter_bloc_texte;

    PROCEDURE ajouter_bloc_media(
        p_identifiant_article NUMBER,
        p_code_type_bloc VARCHAR2,
        p_ordre_affichage NUMBER,
        p_identifiant_ressource_media NUMBER,
        p_texte_alternatif VARCHAR2,
        p_legende VARCHAR2 DEFAULT NULL
    ) IS
        v_code_type_bloc VARCHAR2(30 CHAR) := LOWER(TRIM(p_code_type_bloc));
        v_code_type_media VARCHAR2(30 CHAR);
    BEGIN
        IF v_code_type_bloc NOT IN ('image', 'video') THEN
            RAISE_APPLICATION_ERROR(-20706, 'Type de bloc media invalide.');
        END IF;

        IF TRIM(p_texte_alternatif) IS NULL OR LENGTH(TRIM(p_texte_alternatif)) > 180 THEN
            RAISE_APPLICATION_ERROR(-20707, 'Texte alternatif media invalide.');
        END IF;

        IF p_legende IS NOT NULL AND LENGTH(TRIM(p_legende)) > 220 THEN
            RAISE_APPLICATION_ERROR(-20708, 'Legende media trop longue.');
        END IF;

        SELECT rtm.code_type_media
          INTO v_code_type_media
          FROM ressource_media rm
          JOIN ref_type_media rtm
            ON rtm.identifiant_type_media = rm.identifiant_type_media
         WHERE rm.identifiant_ressource_media = p_identifiant_ressource_media;

        IF v_code_type_media != v_code_type_bloc THEN
            RAISE_APPLICATION_ERROR(-20709, 'Le type du media ne correspond pas au bloc.');
        END IF;

        INSERT INTO article_bloc (
            identifiant_article,
            code_type_bloc,
            identifiant_ressource_media,
            ordre_affichage,
            texte_alternatif,
            legende
        ) VALUES (
            p_identifiant_article,
            v_code_type_bloc,
            p_identifiant_ressource_media,
            p_ordre_affichage,
            TRIM(p_texte_alternatif),
            NULLIF(TRIM(p_legende), '')
        );
    END ajouter_bloc_media;
END pkg_article_editor;
