CREATE TABLE article_bloc (
    identifiant_article_bloc NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_article NUMBER NOT NULL,
    code_type_bloc VARCHAR2(30 CHAR) NOT NULL,
    identifiant_ressource_media NUMBER NULL,
    ordre_affichage NUMBER(6) NOT NULL,
    texte CLOB NULL,
    texte_alternatif VARCHAR2(180 CHAR) NULL,
    legende VARCHAR2(220 CHAR) NULL,
    cree_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    mis_a_jour_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_article_bloc_ordre UNIQUE (identifiant_article, ordre_affichage),
    CONSTRAINT ck_article_bloc_ordre CHECK (ordre_affichage > 0),
    CONSTRAINT ck_article_bloc_contenu CHECK (
        (
            code_type_bloc IN ('paragraphe', 'sous_titre')
            AND texte IS NOT NULL
            AND identifiant_ressource_media IS NULL
        )
        OR
        (
            code_type_bloc IN ('image', 'video')
            AND identifiant_ressource_media IS NOT NULL
            AND texte IS NULL
            AND texte_alternatif IS NOT NULL
        )
    ),
    CONSTRAINT fk_article_bloc_article
        FOREIGN KEY (identifiant_article)
        REFERENCES article (identifiant_article)
        ON DELETE CASCADE,
    CONSTRAINT fk_article_bloc_type
        FOREIGN KEY (code_type_bloc)
        REFERENCES ref_type_bloc_article (code_type_bloc),
    CONSTRAINT fk_article_bloc_media
        FOREIGN KEY (identifiant_ressource_media)
        REFERENCES ressource_media (identifiant_ressource_media)
);

CREATE INDEX idx_article_bloc_article ON article_bloc (identifiant_article, ordre_affichage);
CREATE INDEX idx_article_bloc_media ON article_bloc (identifiant_ressource_media);

CREATE OR REPLACE VIEW vw_article_blocs_ordonnes AS
SELECT ab.identifiant_article_bloc,
       ab.identifiant_article,
       a.titre AS article_titre,
       a.auteur_affiche,
       ab.ordre_affichage,
       ab.code_type_bloc,
       rtba.libelle_type_bloc,
       ab.texte,
       ab.texte_alternatif,
       ab.legende,
       rm.identifiant_ressource_media,
       rm.titre AS media_titre,
       rm.type_mime,
       rm.nom_fichier_original,
       rem.uri_stockage
  FROM article_bloc ab
  JOIN article a
    ON a.identifiant_article = ab.identifiant_article
  JOIN ref_type_bloc_article rtba
    ON rtba.code_type_bloc = ab.code_type_bloc
  LEFT JOIN ressource_media rm
    ON rm.identifiant_ressource_media = ab.identifiant_ressource_media
  LEFT JOIN reference_externe_media rem
    ON rem.identifiant_ressource_media = rm.identifiant_ressource_media;
/

CREATE OR REPLACE VIEW vw_admin_articles AS
SELECT a.identifiant_article,
       a.titre,
       a.slug,
       a.resume,
       a.auteur_affiche,
       rsa.code_statut,
       rsa.libelle_statut,
       a.soumis_le,
       a.publie_le,
       a.cree_le,
       a.mis_a_jour_le,
       cm.adresse_courriel AS auteur_courriel,
       pm.prenom,
       pm.nom,
       COUNT(DISTINCT ra.identifiant_revision_article) AS total_revisions,
       COUNT(DISTINCT ab.identifiant_article_bloc) AS total_blocs
  FROM article a
  JOIN ref_statut_article rsa
    ON rsa.identifiant_statut_article = a.identifiant_statut_article
  JOIN compte_membre cm
    ON cm.identifiant_compte_membre = a.identifiant_compte_auteur
  LEFT JOIN profil_membre pm
    ON pm.identifiant_compte_membre = cm.identifiant_compte_membre
  LEFT JOIN revision_article ra
    ON ra.identifiant_article = a.identifiant_article
  LEFT JOIN article_bloc ab
    ON ab.identifiant_article = a.identifiant_article
 GROUP BY a.identifiant_article,
          a.titre,
          a.slug,
          a.resume,
          a.auteur_affiche,
          rsa.code_statut,
          rsa.libelle_statut,
          a.soumis_le,
          a.publie_le,
          a.cree_le,
          a.mis_a_jour_le,
          cm.adresse_courriel,
          pm.prenom,
          pm.nom;
