CREATE TABLE autorisation_droits_media (
    identifiant_autorisation_droits_media NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_ressource_media NUMBER NOT NULL,
    identifiant_statut_droits_media NUMBER NOT NULL,
    nom_titulaire_droits VARCHAR2(200 CHAR) NOT NULL,
    reference_consentement VARCHAR2(200 CHAR) NULL,
    perimetre_autorisation VARCHAR2(200 CHAR) NOT NULL,
    autorise_le TIMESTAMP WITH TIME ZONE NOT NULL,
    expire_le TIMESTAMP WITH TIME ZONE NULL,
    commentaire_revision VARCHAR2(500 CHAR) NULL,
    cree_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    mis_a_jour_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_autorisation_droits_media_dates CHECK (expire_le IS NULL OR expire_le >= autorise_le),
    CONSTRAINT fk_autorisation_droits_media_ressource
        FOREIGN KEY (identifiant_ressource_media)
        REFERENCES ressource_media (identifiant_ressource_media),
    CONSTRAINT fk_autorisation_droits_media_statut
        FOREIGN KEY (identifiant_statut_droits_media)
        REFERENCES ref_statut_droits_media (identifiant_statut_droits_media)
);

