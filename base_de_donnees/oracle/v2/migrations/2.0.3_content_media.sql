CREATE TABLE article (
    identifiant_article NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_compte_auteur NUMBER NOT NULL,
    identifiant_statut_article NUMBER NOT NULL,
    titre VARCHAR2(200 CHAR) NOT NULL,
    slug VARCHAR2(220 CHAR) NOT NULL,
    resume VARCHAR2(500 CHAR) NOT NULL,
    contenu CLOB NOT NULL,
    soumis_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    publie_le TIMESTAMP WITH TIME ZONE NULL,
    cree_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    mis_a_jour_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_article_slug UNIQUE (slug),
    CONSTRAINT fk_article_auteur
        FOREIGN KEY (identifiant_compte_auteur)
        REFERENCES compte_membre (identifiant_compte_membre),
    CONSTRAINT fk_article_statut
        FOREIGN KEY (identifiant_statut_article)
        REFERENCES ref_statut_article (identifiant_statut_article)
);

CREATE TABLE revision_article (
    identifiant_revision_article NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_article NUMBER NOT NULL,
    identifiant_compte_relecteur NUMBER NOT NULL,
    identifiant_decision_revision_article NUMBER NOT NULL,
    commentaire_revision CLOB NULL,
    decide_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    cree_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_revision_article_article
        FOREIGN KEY (identifiant_article)
        REFERENCES article (identifiant_article),
    CONSTRAINT fk_revision_article_relecteur
        FOREIGN KEY (identifiant_compte_relecteur)
        REFERENCES compte_membre (identifiant_compte_membre),
    CONSTRAINT fk_revision_article_decision
        FOREIGN KEY (identifiant_decision_revision_article)
        REFERENCES ref_decision_revision_article (identifiant_decision_revision_article)
);

CREATE TABLE ressource_media (
    identifiant_ressource_media NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_type_media NUMBER NOT NULL,
    identifiant_mode_stockage_media NUMBER NOT NULL,
    identifiant_statut_media NUMBER NOT NULL,
    identifiant_compte_depot NUMBER NULL,
    titre VARCHAR2(200 CHAR) NOT NULL,
    description_media VARCHAR2(500 CHAR) NULL,
    nom_fichier_original VARCHAR2(255 CHAR) NOT NULL,
    type_mime VARCHAR2(120 CHAR) NOT NULL,
    taille_octets NUMBER(19) NOT NULL,
    largeur_px NUMBER(10) NULL,
    hauteur_px NUMBER(10) NULL,
    duree_secondes NUMBER(10,3) NULL,
    texte_alternatif VARCHAR2(300 CHAR) NULL,
    date_capture DATE NULL,
    valide_par_identifiant_compte NUMBER NULL,
    valide_le TIMESTAMP WITH TIME ZONE NULL,
    cree_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    mis_a_jour_le TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ressource_media_taille CHECK (taille_octets >= 0),
    CONSTRAINT fk_ressource_media_type
        FOREIGN KEY (identifiant_type_media)
        REFERENCES ref_type_media (identifiant_type_media),
    CONSTRAINT fk_ressource_media_mode
        FOREIGN KEY (identifiant_mode_stockage_media)
        REFERENCES ref_mode_stockage_media (identifiant_mode_stockage_media),
    CONSTRAINT fk_ressource_media_statut
        FOREIGN KEY (identifiant_statut_media)
        REFERENCES ref_statut_media (identifiant_statut_media),
    CONSTRAINT fk_ressource_media_depot
        FOREIGN KEY (identifiant_compte_depot)
        REFERENCES compte_membre (identifiant_compte_membre),
    CONSTRAINT fk_ressource_media_validateur
        FOREIGN KEY (valide_par_identifiant_compte)
        REFERENCES compte_membre (identifiant_compte_membre)
);

CREATE TABLE charge_binaire_media (
